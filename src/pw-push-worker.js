/**
 * Playwright Push Worker ("The Committer")
 *
 * Receives generated test files + PR metadata from pw-generate (or directly
 * from playwright-worker during migration) and:
 *   1. Gets the branch tip ref
 *   2. Checks which files already exist (parallel)
 *   3. Pushes a single commit with all test files
 *   4. Triggers the test pipeline
 *   5. Posts a PR comment with the summary
 *
 * Subrequest budget: ~N+4 (N = number of generated test files)
 * Typical worst case: ~14 subrequests (10 files + 4 fixed calls)
 */

import { orgUrl, AZURE_API_VERSION } from "./lib/azure.js";
import { postComment } from "./lib/comments.js";
import { fetchWithTimeout } from "./lib/fetch.js";

const PLAYWRIGHT_TEST_BRANCH = "internship/playwright-unit-tests";

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);

    // ─── GET / — health check ───
    if (request.method === "GET" && url.pathname === "/") {
      return new Response("pw-push worker is running", { status: 200 });
    }

    if (request.method !== "POST") {
      return new Response("Only POST allowed", { status: 405 });
    }

    let payload;
    try {
      payload = await request.json();
    } catch {
      return new Response("Invalid JSON", { status: 400 });
    }

    // Validate required fields
    const { project, repoId, prId, generatedTests, componentFiles, docsCount, azureToken } = payload;
    if (!project || !repoId || !prId || !generatedTests || !azureToken) {
      return new Response(
        "Missing required fields: project, repoId, prId, generatedTests, azureToken",
        { status: 400 }
      );
    }

    console.log(`(log) [PW-Push] Received ${generatedTests.length} test file(s) for PR #${prId}`);

    // Run non-blocking
    ctx.waitUntil(pushFlow(payload, env));

    return new Response("Accepted", { status: 202 });
  },
};

// ─── Main Push Flow ──────────────────────────────────────────────────────────

async function pushFlow(payload, env) {
  const { project, repoId, prId, generatedTests, componentFiles, docsCount, azureToken, errorMsg } = payload;
  const pipelineId = parseInt(env?.PIPELINE_ID || "88", 10);
  const azureHeaders = {
    Authorization: `Basic ${btoa(":" + azureToken)}`,
  };

  try {
    // 1. Push generated tests to the test branch
    const pushResult = await pushTests(project, repoId, generatedTests, prId, azureHeaders, env);
    console.log(`(log) [PW-Push] Push result: ${pushResult.success ? "success" : "failed"}`);

    // 2. Trigger pipeline
    let pipelineTriggered = false;
    if (pushResult.success) {
      pipelineTriggered = await triggerPipeline(project, azureHeaders, env, pipelineId);
      console.log(`(log) [PW-Push] Pipeline trigger: ${pipelineTriggered ? "success" : "failed"}`);
    }

    // 3. Post PR comment with summary
    const comment = buildComment(
      generatedTests,
      componentFiles || [],
      docsCount || 0,
      errorMsg || null,
      pushResult.success,
      pipelineTriggered,
      pipelineId
    );
    await postComment(env, project, repoId, prId, azureHeaders, comment, "PW-Push");

    console.log(`(log) [PW-Push] Push flow completed for PR #${prId}`);
  } catch (e) {
    console.error("(log) [PW-Push] Flow error:", e.stack || e.message);
    try {
      await postComment(env, project, repoId, prId, azureHeaders,
        `## 🎭 Playwright Test Generation\n\n❌ An error occurred during push:\n\`${e.message}\`\n\n---\n_Generated by AI PR Review Bot — Playwright Push Worker_`,
        "PW-Push");
    } catch (commentErr) {
      console.error("(log) [PW-Push] Could not post error comment:", commentErr.message);
    }
  }
}

// ─── Push Tests to Branch ────────────────────────────────────────────────────

async function pushTests(project, repoId, generatedTests, prId, azureHeaders, env) {
  const ORG = orgUrl(env);
  try {
    // 1. Get the branch tip ref
    const refsUrl = `${ORG}/${project}/_apis/git/repositories/${repoId}/refs?filter=heads/${PLAYWRIGHT_TEST_BRANCH}&api-version=${AZURE_API_VERSION}`;
    const refsRes = await fetchWithTimeout(refsUrl, { headers: azureHeaders });

    if (!refsRes.ok) {
      console.error(`(log) [PW-Push] Failed to get branch ref: ${refsRes.status}`);
      return { success: false, message: `Failed to get branch ref: ${refsRes.status}` };
    }

    const refsData = await refsRes.json();
    const branchRef = (refsData.value || []).find(
      r => r.name === `refs/heads/${PLAYWRIGHT_TEST_BRANCH}`
    );

    if (!branchRef) {
      console.error("(log) [PW-Push] Branch not found:", PLAYWRIGHT_TEST_BRANCH);
      return { success: false, message: `Branch ${PLAYWRIGHT_TEST_BRANCH} not found` };
    }

    const oldObjectId = branchRef.objectId;
    console.log(`(log) [PW-Push] Branch tip: ${oldObjectId}`);

    // 2. Check which files already exist (in parallel)
    const existChecks = await Promise.allSettled(
      generatedTests.map(async (test) => {
        const checkUrl = `${ORG}/${project}/_apis/git/repositories/${repoId}/items?path=${encodeURIComponent("/" + test.filePath)}&versionDescriptor.version=${encodeURIComponent(PLAYWRIGHT_TEST_BRANCH)}&versionDescriptor.versionType=branch&api-version=${AZURE_API_VERSION}`;
        const checkRes = await fetchWithTimeout(checkUrl, { headers: azureHeaders, method: "HEAD" });
        return { test, exists: checkRes.ok };
      })
    );

    const changes = existChecks
      .filter(r => r.status === "fulfilled")
      .map(r => {
        const { test, exists } = r.value;
        console.log(`(log) [PW-Push] File ${test.filePath}: ${exists ? "edit" : "add"}`);
        return {
          changeType: exists ? "edit" : "add",
          item: { path: "/" + test.filePath },
          newContent: { content: test.content, contentType: "rawtext" },
        };
      });

    // 3. Push all files in a single commit
    const pushUrl = `${ORG}/${project}/_apis/git/repositories/${repoId}/pushes?api-version=${AZURE_API_VERSION}`;
    const pushBody = {
      refUpdates: [
        {
          name: `refs/heads/${PLAYWRIGHT_TEST_BRANCH}`,
          oldObjectId,
        },
      ],
      commits: [
        {
          comment: `[AI] Playwright tests for PR #${prId}`,
          changes,
        },
      ],
    };

    const pushRes = await fetchWithTimeout(pushUrl, {
      method: "POST",
      headers: { ...azureHeaders, "Content-Type": "application/json" },
      body: JSON.stringify(pushBody),
      timeout: 15_000,
    });

    if (pushRes.ok) {
      console.log("(log) [PW-Push] Push successful");
      return { success: true, message: "Tests pushed successfully" };
    } else {
      const errText = await pushRes.text();
      console.error(`(log) [PW-Push] Push failed: ${pushRes.status}`, errText);
      return { success: false, message: `Push failed: ${pushRes.status}` };
    }
  } catch (e) {
    console.error("(log) [PW-Push] Push error:", e.message);
    return { success: false, message: `Push error: ${e.message}` };
  }
}

// ─── Trigger Pipeline ────────────────────────────────────────────────────────

async function triggerPipeline(project, azureHeaders, env, pipelineId) {
  const ORG = orgUrl(env);
  try {
    const pipelineUrl = `${ORG}/${project}/_apis/pipelines/${pipelineId}/runs?api-version=${AZURE_API_VERSION}`;
    const pipelineBody = {
      resources: {
        repositories: {
          self: {
            refName: `refs/heads/${PLAYWRIGHT_TEST_BRANCH}`,
          },
        },
      },
    };

    const res = await fetchWithTimeout(pipelineUrl, {
      method: "POST",
      headers: { ...azureHeaders, "Content-Type": "application/json" },
      body: JSON.stringify(pipelineBody),
    });

    if (res.ok) {
      const data = await res.json();
      console.log(`(log) [PW-Push] Pipeline ${pipelineId} triggered, run ID: ${data.id || "unknown"}`);
      return true;
    } else {
      console.error(`(log) [PW-Push] Pipeline trigger failed: ${res.status}`, await res.text());
      return false;
    }
  } catch (e) {
    console.error("(log) [PW-Push] Pipeline trigger error:", e.message);
    return false;
  }
}

// ─── Build PR Comment ────────────────────────────────────────────────────────

function buildComment(generatedTests, componentFiles, docsCount, errorMsg, pushSuccess, pipelineTriggered, pipelineId) {
  const body = [`## 🎭 Playwright Test Generation`, ``];

  if (errorMsg) {
    body.push(`⚠️ ${errorMsg}`, ``);
  } else {
    body.push(`Generated **${generatedTests.length}** test file(s) using **${docsCount}** documentation file(s) as context.`, ``);

    if (pushSuccess) {
      body.push(`✅ Tests pushed to \`${PLAYWRIGHT_TEST_BRANCH}\``);
      if (pipelineTriggered) {
        body.push(`✅ Pipeline #${pipelineId} triggered`);
      } else {
        body.push(`⚠️ Pipeline trigger failed — run manually if needed`);
      }
    } else {
      body.push(`❌ Could not push tests to branch — see worker logs for details`);
    }
    body.push(``);

    // List generated test files
    if (generatedTests.length > 0) {
      body.push(`### Generated Test Files`);
      for (const t of generatedTests) {
        body.push(`- \`${t.filePath}\``);
      }
      body.push(``);
    }
  }

  // List changed components
  if (componentFiles.length > 0) {
    body.push(`### Changed Components Analyzed`);
    for (const f of componentFiles) {
      body.push(`- \`${f.path}\``);
    }
    body.push(``);
  }

  body.push(`---`, `_Generated by AI PR Review Bot — Playwright Test Gen_`);
  return body.join("\n");
}
